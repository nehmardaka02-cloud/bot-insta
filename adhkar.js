function pickFrom(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function formatDhikr(d) {
  return `🕌 «${d.text}»\n\n📖 المصدر: ${d.source}\n✨ ﴿وَذَكِّرْ فَإِنَّ الذِّكْرَىٰ تَنفَعُ الْمُؤْمِنِينَ﴾`;
}

function buildReply(text = "") {
  const t = (text || "").toLowerCase();

  if (["سلام", "مرحبا", "هلا", "hi", "hello", "salam", "/start"].some(w => t.includes(w))) {
    return (
      "🕌 أهلاً وسهلاً بيك في بوت الأذكار!\n\n" +
      "كل مرة تراسلني أرسل ليك ذكرًا من القرآن والسنة 📖\n\n" +
      "🌅 اكتب «صباح» → أذكار الصباح\n" +
      "🌙 اكتب «مساء» → أذكار المساء\n" +
      "📖 اكتب «آية» → آية من القرآن\n" +
      "💎 أي كلام آخر → ذكر يريح القلب\n\n" +
      "المصادر مذكورة تحت كل ذكر 🤍"
    );
  }

  if (t.includes("صباح")) return formatDhikr(pickFrom(adhkarData.morning)) + "\n\n🌅 نهار مبارك بإذن الله";
  if (t.includes("مساء") || t.includes("مسا")) return formatDhikr(pickFrom(adhkarData.evening)) + "\n\n🌙 ليلة مباركة بإذن الله";
  if (t.includes("آية") || t.includes("اية")) return formatDhikr(pickFrom(adhkarData.ayat));

  return formatDhikr(pickFrom(adhkarData.general));
}

